// Regenerates js/t2s-map.js (Traditional → Simplified, only for characters the app uses).
// Usage: npm i --no-save opencc-js && node scripts/gen-t2s.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import * as OpenCC from 'opencc-js';

const root = new URL('..', import.meta.url).pathname;
const files = [];
const walk = (d) => readdirSync(d).forEach((f) => {
  const p = join(d, f);
  if (statSync(p).isDirectory()) walk(p);
  else if (p.endsWith('.js') && !p.endsWith('t2s-map.js')) files.push(p);
});
walk(join(root, 'js'));
walk(join(root, 'scripts'));

const chars = new Set();
for (const f of files) for (const ch of readFileSync(f, 'utf8')) if (/[㐀-鿿]/.test(ch)) chars.add(ch);

const conv = OpenCC.Converter({ from: 'hk', to: 'cn' });
const map = {};
for (const ch of [...chars].sort()) {
  const s = conv(ch);
  if (s !== ch) map[ch] = s;
}
const keys = Object.keys(map);
const out = `// Generated by scripts/gen-t2s.mjs — do not edit by hand.\nexport const T2S_FROM = ${JSON.stringify(keys.join(''))};\nexport const T2S_TO = ${JSON.stringify(keys.map((k) => map[k]).join(''))};\n`;
writeFileSync(join(root, 'js/t2s-map.js'), out);
console.log(`${chars.size} chars scanned, ${keys.length} mapped`);
